using FluentResults;
using WardenId.SharedKernel.Domain;
using WardenId.SharedKernel.Domain.Utilities;
using WardenId.Tenancy.Domain.Events;

namespace WardenId.Tenancy.Domain;

public sealed class Tenant : AggregateRoot, IAuditableAggregate, ICreationTracked
{
    // Tenant settings are platform configuration, so admin.config rather than admin.directory (users).
    // Signing keys are diffed too (a rotation or retirement changes only them); their key material is
    // redacted — the public JWK as well, since JWKS already publishes it and the log needn't repeat it.
    private static readonly IReadOnlySet<string> AuditSensitive = new HashSet<string>
    {
        $"{nameof(SigningKeys)}.{nameof(SigningKey.EncryptedPrivateKey)}",
        $"{nameof(SigningKeys)}.{nameof(SigningKey.PublicKeyJwk)}"
    };

    private static readonly IReadOnlySet<string> AuditNavigations = new HashSet<string> { nameof(SigningKeys) };

    public string AuditTargetTypeKey => AuditTargetTypeKeys.Tenant;
    public AuditableChannel AuditChannel => AuditableChannel.AdminConfig;
    public IReadOnlySet<string> AuditSensitivePropertyNames => AuditSensitive;
    public IReadOnlySet<string> AuditedNavigationNames => AuditNavigations;

    private Tenant(
        Slug slug,
        string displayName)
    {
        Slug = slug;
        DisplayName = displayName;
        Status = Status.Provisioning;
    }

    public string DisplayName { get; private set; }
    public Slug Slug { get; private set; }
    public Status Status { get; private set; }
    public DateTimeOffset? SuspendedAtUtc { get; private set; }
    public string? SuspendedReason { get; private set; }
    public DateTimeOffset CreatedAt { get; private set; }
    public uint Version { get; private set; }

    private readonly List<SigningKey> _signingKeys = new();
    public IReadOnlyCollection<SigningKey> SigningKeys => _signingKeys.AsReadOnly();

    public static Result<Tenant> Create(Slug slug, string displayName)
    {
        var displayNameResult = ValidateDisplayName(displayName);
        if (displayNameResult.IsFailed) return Result.Fail(displayNameResult.Errors);

        var tenant = new Tenant(slug, displayNameResult.Value);
        tenant.RaiseDomainEvent(new TenantCreatedDomainEvent(tenant.Slug));
        return Result.Ok(tenant);
    }

    /// <summary>Changes the display name. The slug (and so the issuer) never changes.</summary>
    public Result Rename(string displayName)
    {
        if (Status == Status.Archived) return Result.Fail(TenantErrors.TenantInvalidTransition(Status));

        var displayNameResult = ValidateDisplayName(displayName);
        if (displayNameResult.IsFailed) return Result.Fail(displayNameResult.Errors);
        if (displayNameResult.Value == DisplayName) return Result.Ok();

        DisplayName = displayNameResult.Value;
        RaiseDomainEvent(new TenantRenamedDomainEvent(DisplayName));
        return Result.Ok();
    }

    private static Result<string> ValidateDisplayName(string displayName)
    {
        if (string.IsNullOrWhiteSpace(displayName)) return Result.Fail(TenantErrors.TenantDisplayNameRequired());

        var trimmed = displayName.Trim();
        return trimmed.Length > 200 ? Result.Fail(TenantErrors.TenantDisplayNameTooLong()) : Result.Ok(trimmed);
    }

    /// <summary>
    /// Attaches the tenant's initial signing key. Call once, right after Create and before
    /// Activate. Key material generation and encryption at rest happen in the application/
    /// infrastructure layer before this call — the aggregate only records the result.
    /// </summary>
    public Result AssignInitialSigningKey(SigningKey signingKey)
    {
        if (_signingKeys.Count > 0) return Result.Fail(TenantErrors.TenantSigningKeyAlreadyAssigned());

        _signingKeys.Add(signingKey);
        RaiseDomainEvent(new TenantSigningKeyAssignedDomainEvent(signingKey.Id));
        return Result.Ok();
    }

    /// <summary>
    /// Makes <paramref name="newKey"/> the signing key. The previous active key becomes
    /// Retiring: it stops signing but stays in JWKS so tokens it already signed still verify.
    /// Not allowed on an archived tenant. Key material is generated by the caller, as for
    /// <see cref="AssignInitialSigningKey"/>.
    /// </summary>
    public Result RotateSigningKey(SigningKey newKey)
    {
        if (Status == Status.Archived) return Result.Fail(TenantErrors.TenantInvalidTransition(Status));

        if (!newKey.IsActive || _signingKeys.Any(k => k.SigningKeyId == newKey.SigningKeyId))
            return Result.Fail(TenantErrors.SigningKeyNotNew());

        var previous = _signingKeys.FirstOrDefault(k => k.IsActive);
        previous?.BeginRetiring();

        _signingKeys.Add(newKey);
        RaiseDomainEvent(new TenantSigningKeyRotatedDomainEvent(newKey.SigningKeyId, previous?.SigningKeyId));
        return Result.Ok();
    }

    /// <summary>
    /// Retiring -> Retired: the key leaves JWKS and tokens it signed stop verifying. Manual
    /// on purpose — the caller should wait at least the longest token lifetime after the
    /// rotation (see <see cref="SigningKey.RetiringSince"/>); this aggregate doesn't know
    /// token lifetimes, which are Protocol configuration. The active key can't be retired;
    /// rotate first.
    /// </summary>
    public Result RetireSigningKey(Guid signingKeyId)
    {
        if (Status == Status.Archived) return Result.Fail(TenantErrors.TenantInvalidTransition(Status));

        var key = _signingKeys.FirstOrDefault(k => k.SigningKeyId == signingKeyId);
        if (key is null) return Result.Fail(TenantErrors.SigningKeyNotFound);

        switch (key.Status)
        {
            case SigningKeyStatus.Active:
                return Result.Fail(TenantErrors.SigningKeyActiveCannotBeRetired());
            case SigningKeyStatus.Retired:
                return Result.Fail(TenantErrors.SigningKeyAlreadyRetired());
        }

        key.Retire();
        RaiseDomainEvent(new TenantSigningKeyRetiredDomainEvent(key.SigningKeyId));
        return Result.Ok();
    }

    /// <summary>
    /// Provisioning -> Active. Requires an active signing key to already be assigned —
    /// enforces "signing keys mandatory" as an aggregate invariant, not caller discipline.
    /// </summary>
    public Result Activate()
    {
        if (Status != Status.Provisioning) return Result.Fail(TenantErrors.TenantInvalidTransition(Status));

        if (!_signingKeys.Any(k => k.IsActive)) return Result.Fail(TenantErrors.TenantNoActiveSigningKey());

        Status = Status.Active;
        RaiseDomainEvent(new TenantActivatedDomainEvent());
        return Result.Ok();
    }

    public Result Suspend(string reason)
    {
        if (Status != Status.Active) return Result.Fail(TenantErrors.TenantInvalidTransition(Status));

        if (string.IsNullOrWhiteSpace(reason)) return Result.Fail(TenantErrors.TenantSuspendReasonRequired());

        Status = Status.Suspended;
        SuspendedAtUtc = DateTimeOffset.UtcNow;
        SuspendedReason = reason.Trim();
        RaiseDomainEvent(new TenantSuspendedDomainEvent(SuspendedReason));
        return Result.Ok();
    }

    public Result Reactivate()
    {
        if (Status != Status.Suspended) return Result.Fail(TenantErrors.TenantInvalidTransition(Status));

        Status = Status.Active;
        SuspendedAtUtc = null;
        SuspendedReason = null;
        RaiseDomainEvent(new TenantReactivatedDomainEvent());
        return Result.Ok();
    }

    /// <summary>Terminal state — an archived tenant can never be reactivated.</summary>
    public Result Archive()
    {
        if (Status == Status.Archived) return Result.Fail(TenantErrors.TenantAlreadyArchived());

        Status = Status.Archived;
        RaiseDomainEvent(new TenantArchivedDomainEvent());
        return Result.Ok();
    }
}